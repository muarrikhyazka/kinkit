#!/usr/bin/env python3
"""One-off import of the household "rumahbot" state into a Kinkit account.

Python stdlib only. It does not connect to the database: it prints one SQL
transaction to stdout. Review it, then pipe it into psql. Every statement is
idempotent, so running it twice changes nothing.

What it imports
  * learned_keywords.json (keyword -> category)   -> category_keywords
    (category names are matched case-insensitively to the account's
    categories; existing keywords are kept unless --overwrite-keywords)
  * <data-dir>/mandatory_ingredients.json  (list)  -> mandatory_ingredients
  * weekly meal plan post: reminder_schedules job 'meal_plan', from the
    "meal" override in <data-dir>/reminder_schedule.json or rumahbot's
    default Friday 06:00 (household time); --no-meal-post leaves it off
  * rumahbot's two plain chat nudges become Kinkit reminders (they are sent
    by Kinkit's reminders worker, with Done/Snooze buttons):
      - daily 20:00   "Log today's spending ..." (spend)
      - Thursday 20:30 "Must-use ingredients for next week? ..." (bahan_remind)
    (/jadwal overrides in reminder_schedule.json are honoured;
    --no-reminders skips them)
Not imported (nothing to carry over): grocery_deals.json / scrape cache
(Kinkit scrapes itself, see MEAL_PROMO_STORES), reminder_runs.json and
last_*.txt (run markers of jobs already moved into Kinkit reminders), the
in-memory /tanggal override.

Usage (tatadana, account 1):
  docker cp rumahbot:/app/data ./rumahbot-data          # read-only copy of the volume
  python3 bots/scripts/import_rumahbot.py --account 1 \\
      --keywords /home/muarrikh/apps/rumahbot/learned_keywords.json \\
      --data-dir ./rumahbot-data > rumahbot-import.sql
  less rumahbot-import.sql
  docker exec -i tatadana-postgres sh -c \\
      'psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "${POSTGRES_DB:-$POSTGRES_USER}"' < rumahbot-import.sql
"""
import argparse
import json
import os
import sys

DOW = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]
DEFAULTS = {  # rumahbot REMINDER_JOBS (days 0=Sun..6=Sat, household time)
    "spend": {"days": [0, 1, 2, 3, 4, 5, 6], "hour": 20, "minute": 0},
    "bahan_remind": {"days": [4], "hour": 20, "minute": 30},
    "meal": {"days": [5], "hour": 6, "minute": 0},
}
SPEND_TITLE = "Log today's spending (type it in the chat, e.g. lunch 50k)"
BAHAN_TITLE = "Must-use ingredients for next week? Add: /addingredient chicken, remove: /removeingredient chicken, list: /ingredients"
# Titles earlier imports used; an account that already has one is not given a duplicate.
LEGACY_TITLES = {
    SPEND_TITLE: "Catat pengeluaran hari ini (ketik di grup, contoh: makan siang 50rb)",
    BAHAN_TITLE: "Bahan masakan minggu depan? Tambah: /tambahbahan ayam, hapus: /hapusbahan ayam, lihat: /bahan",
}


def q(s):
    """SQL string literal."""
    return "'" + str(s).replace("'", "''") + "'"


def load_json(path, default):
    if not path or not os.path.exists(path):
        return default
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def schedule(overrides, name):
    spec = dict(DEFAULTS[name])
    o = overrides.get(name)
    if isinstance(o, dict) and o.get("days") is not None:
        spec.update(days=sorted(set(int(d) for d in o["days"])), hour=int(o["hour"]), minute=int(o["minute"]))
        spec["start_date"] = o.get("start_date")
    return spec


def reminder_sql(aid, title, spec, category):
    days = spec["days"]
    tod = f"{spec['hour']:02d}:{spec['minute']:02d}"
    if len(days) == 7:
        kind, weekdays = "daily", "'{}'::int[]"
    else:
        kind, weekdays = "weekly", "ARRAY[" + ",".join(str(d) for d in days) + "]::int[]"
    titles = ", ".join(q(t) for t in (title, LEGACY_TITLES.get(title)) if t)
    start = q(spec["start_date"]) + "::date" if spec.get("start_date") else "CURRENT_DATE"
    return (
        "INSERT INTO reminders (account_id, title, kind, time_of_day, weekdays, start_date, category)\n"
        f"SELECT {aid}, {q(title)}, {q(kind)}, {q(tod)}, {weekdays}, {start}, {q(category)}\n"
        f"WHERE NOT EXISTS (SELECT 1 FROM reminders WHERE account_id={aid} AND title IN ({titles}));"
    )


def build_sql(aid, keywords, ingredients, overrides, meal_post=True, reminders=True, overwrite=False):
    out = ["-- rumahbot -> Kinkit import (generated by bots/scripts/import_rumahbot.py)",
           "BEGIN;",
           f"DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM users WHERE id={aid}) THEN RAISE EXCEPTION 'account {aid} not found'; END IF; END $$;"]

    rows = [(str(k).strip().lower(), str(v).strip()) for k, v in keywords.items()
            if str(k).strip() and str(v).strip() and not str(k).startswith("_")]
    if rows:
        out.append(f"\n-- {len(rows)} learned spending keywords")
        values = ",\n  ".join(f"({q(k)}, {q(c)})" for k, c in sorted(rows))
        conflict = "DO UPDATE SET category=EXCLUDED.category" if overwrite else "DO NOTHING"
        out.append(
            "INSERT INTO category_keywords (account_id, keyword, category)\n"
            f"SELECT {aid}, v.kw, COALESCE((SELECT c.name FROM categories c WHERE c.account_id={aid} AND lower(c.name)=lower(v.cat) ORDER BY c.id LIMIT 1), v.cat)\n"
            f"FROM (VALUES\n  {values}\n) AS v(kw, cat)\n"
            f"ON CONFLICT (account_id, keyword) {conflict};"
        )

    ings = sorted({" ".join(str(i).lower().split()) for i in ingredients if str(i).strip()})
    if ings:
        out.append(f"\n-- {len(ings)} must-use ingredients")
        for i in ings:
            out.append(f"INSERT INTO mandatory_ingredients (account_id, name) VALUES ({aid}, {q(i)}) ON CONFLICT DO NOTHING;")

    meal = schedule(overrides, "meal")
    start = q(meal["start_date"]) + "::date" if meal.get("start_date") else "NULL"
    days_s = ", ".join(DOW[d] for d in meal["days"])
    out.append(f"\n-- weekly meal plan post: {days_s} {meal['hour']:02d}:{meal['minute']:02d} household time, "
               f"{'on' if meal_post else 'off'} (an existing schedule is left alone)")
    out.append(
        "INSERT INTO reminder_schedules (account_id, job_name, days, hour, minute, enabled, start_date)\n"
        f"VALUES ({aid}, 'meal_plan', {q(','.join(str(d) for d in meal['days']))}, {meal['hour']}, {meal['minute']}, "
        f"{'TRUE' if meal_post else 'FALSE'}, {start})\n"
        "ON CONFLICT (account_id, job_name) DO NOTHING;"
    )

    if reminders:
        out.append("\n-- rumahbot chat nudges as Kinkit reminders (skipped if a reminder with the same title exists)")
        out.append(reminder_sql(aid, SPEND_TITLE, schedule(overrides, "spend"), "other"))
        out.append(reminder_sql(aid, BAHAN_TITLE, schedule(overrides, "bahan_remind"), "cooking"))

    out.append("\nCOMMIT;")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--account", type=int, required=True, help="Kinkit account id (users.id), e.g. 1 for tatadana")
    ap.add_argument("--keywords", help="path to rumahbot learned_keywords.json")
    ap.add_argument("--data-dir", help="copy of rumahbot's /app/data (mandatory_ingredients.json, reminder_schedule.json)")
    ap.add_argument("--no-meal-post", action="store_true", help="import the meal plan schedule switched off")
    ap.add_argument("--no-reminders", action="store_true", help="don't create the spend / ingredients reminders")
    ap.add_argument("--overwrite-keywords", action="store_true", help="re-map keywords that already exist in Kinkit")
    a = ap.parse_args(argv)
    keywords = load_json(a.keywords, {})
    if a.keywords and not keywords:
        print(f"warning: no keywords read from {a.keywords}", file=sys.stderr)
    data = a.data_dir or ""
    ingredients = load_json(os.path.join(data, "mandatory_ingredients.json"), []) if data else []
    overrides = load_json(os.path.join(data, "reminder_schedule.json"), {}) if data else {}
    sys.stdout.write(build_sql(a.account, keywords, ingredients, overrides,
                               meal_post=not a.no_meal_post, reminders=not a.no_reminders,
                               overwrite=a.overwrite_keywords))
    print(f"-- {len(keywords)} keywords, {len(ingredients)} ingredients, overrides: {sorted(overrides)}", file=sys.stderr)


if __name__ == "__main__":
    main()
